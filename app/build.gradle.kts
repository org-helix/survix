        versionCode = 1
        versionName = "0.1.0"
    }

    signingConfigs {
        // A release key is used when CI provides one (see .github/workflows/release.yml).
        // Otherwise release builds fall back to the debug key so the APK still installs.
        val keystore = System.getenv("SURVIX_KEYSTORE_FILE")
        if (keystore != null) {
            create("release") {
                storeFile = file(keystore)
                storePassword = System.getenv("SURVIX_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("SURVIX_KEY_ALIAS")
                keyPassword = System.getenv("SURVIX_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }

    lint {
        abortOnError = true
        warningsAsErrors = false
        // Translations are checked by hand: French is the default language, English the other.
        disable += "MissingTranslation"
    }
